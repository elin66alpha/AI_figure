if __name__=='__main__':
    main=read('repair-p1-live.json')
    full=read('repair-p1-full-before.json')
    power=read('repair-power-full-before.json')
    # Exact drawing-only deletion: keep all part instances, pin attributes, sheet.
    ids={c['primitiveId'] for c in main['components'] if c['componentType'] not in ('part','sheet')}
    ids|={w['primitiveId'] for w in main['wires']}
    # These magenta legacy frames were generated by our previous layout, not user content.
    ids|={x['primitiveId'] for x in full['pagePrimitives']['rectangles'] if x.get('Color')=='#AA00AA'}
    ids|={x['primitiveId'] for x in full['pagePrimitives']['texts'] if x.get('TextColor')=='#AA00AA'}
    emit('single-sheet-clean-drawing.json',[step('remove-old-wires-and-flags','prim-delete',ids=','.join(sorted(ids)))])
    moves=[]
    for c in main['components']:
        if c['componentType']=='part':
            assert c['designator'] in positions,c['designator']
            x,y=positions[c['designator']]
            moves.append(step('move-'+c['designator'],'modify',id=c['primitiveId'],x=x,y=y))
    emit('single-sheet-move-p1.json',moves)
    copies=[]
    for c in power['components']:
        if c['componentType']!='part': continue
        ref=c['designator']; x,y=positions[ref]
        dev=c['device']
        if ref=='L1': dev={'uuid':'5f542749891744148871d3719304a1eb','libraryUuid':'2cb3ad867dfa4740a0fbae81ea348a21'}
        assert len(dev['uuid'])==32,ref
        # The creation API negates supplied rotation. Match the measured instance.
        copies.append(step('copy-'+ref,'place',designator=ref,lib=dev['libraryUuid'],uuid=dev['uuid'],x=x,y=y,rotation=(-c['rotation'])%360))
    emit('single-sheet-copy-power.json',copies)
    expected={}
    for name in ['repair-p1-live.json','repair-power-live.json']:
        for c in read(name)['components']:
            if c['componentType']=='part':
                assert c['netlistAvailable'],c['designator']
                expected[c['designator']]={p['pinNumber']:p['net'] for p in c['pins']}
    (ROOT/'single-sheet-expected-before.json').write_text(json.dumps(expected,indent=2),encoding='utf-8')
    print('Prepared',len(moves),'preserved parts and',len(copies),'page transfers;',len(ids),'drawing primitives to replace')
