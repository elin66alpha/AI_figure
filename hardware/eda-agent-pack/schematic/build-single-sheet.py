import json
from pathlib import Path

ROOT=Path(__file__).parent
PROJECT='8c5d0d86032348a0a6c85102fe97607e'
PAGE='98cfe13509bc1f5c'
def read(name):
    d=json.loads((ROOT/name).read_text(encoding='utf-8-sig'))
    assert d['ok'],name
    return d['result']
def emit(name,steps):
    (ROOT/name).write_text(json.dumps({'version':1,'meta':{'name':name,'project':PROJECT},'steps':steps},ensure_ascii=False,indent=2),encoding='utf-8')
def step(step_id,run,**flags):
    return {'id':step_id,'run':'sch '+run,'flags':dict(flags,doc=PAGE)}

